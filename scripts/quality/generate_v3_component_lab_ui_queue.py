#!/usr/bin/env python3
"""Deterministically generate UI queue from canonical 66 source candidates."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/"docs/v3/quality/COMPONENT-LAB-FAMILY-QUEUE.json"
DEST=ROOT/"src/Bluent.UI.Demo.Pages/Pages/Components/ComponentLabFamilyQueue.g.cs"
PILOTS={"Button":"button","Icon":"icon","Label":"label","Link":"link"}
def render():
    data=json.loads(SOURCE.read_text(encoding="utf-8"))
    assert data["familyCount"]==66 and data["apiCoverageComplete"] is False
    rows=[]
    for e in data["families"]:
        assert e["completeDemoAcceptance"] is False and e["apiPropertiesEventsMapped"] is False
        name=e["family"].replace('\\','\\\\').replace('"','\\"')
        pilot=PILOTS.get(e["family"])
        assert bool(pilot)==bool(e["scenarioId"])
        rows.append('        new("'+name+'", '+str(e["issue"])+', '+('"'+pilot+'"' if pilot else "null")+'),')
    assert len(rows)==66
    return ("// <auto-generated> Generated from source-family candidates; not v3 acceptance. </auto-generated>\n"
            "#nullable enable\nnamespace Bluent.UI.Demo.Pages.Components;\n"
            "internal static class ComponentLabFamilyQueue\n{\n"
            "    internal sealed record Item(string Name, int Issue, string? PilotId);\n"
            "    internal static readonly Item[] All =\n    [\n"
            +"\n".join(rows)+"\n    ];\n}\n")
if __name__=="__main__":
    parser=argparse.ArgumentParser();parser.add_argument("--check",action="store_true")
    args=parser.parse_args();expected=render()
    if args.check:
        assert DEST.is_file() and DEST.read_text(encoding="utf-8-sig")==expected
        print("Component Lab UI queue 66/66 canonical; 4 pilots, 62 queued.")
    else:
        DEST.write_text(expected,encoding="utf-8")
        print("Generated 66 candidate entries")
